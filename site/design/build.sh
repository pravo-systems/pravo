#!/bin/sh
# Concatenates site/design/css/*.css into site/assets/style.css.
# No minification, no dependencies: tools/sitegen minifies the copy that it
# writes to site/public. Run from anywhere.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
out="$here/../assets/style.css"
{
  printf '/* pravo design system. Generated by site/design/build.sh from site/design/css/*.css. Edit the parts, not this file. */\n'
  for f in "$here"/css/[0-9][0-9]-*.css; do
    printf '\n'
    cat "$f"
  done
} > "$out"
wc -c "$out" | awk '{print "wrote " $2 " (" $1 " bytes)"}'
