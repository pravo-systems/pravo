package schema

import (
	"bytes"
	"fmt"
	"sort"
	"strconv"
	"strings"

	"github.com/hashicorp/terraform-plugin-go/tftypes"
)

// GenOptions selects what GenerateCUE emits. Nil slices mean "everything".
type GenOptions struct {
	Resources   []string
	DataSources []string
	Ephemerals  []string
	// Discoveries are the list resource types a discovery can be built from.
	Discoveries []string
	Functions   []string
	// Header is written as the first comment line (e.g. provider address and version).
	Header string
	// Source is the provider's registry address. Every definition carries it
	// so that pravo can tell which provider a struct belongs to.
	Source string
}

// MetaCUE is the CUE source of the meta fields accepted in resource bodies.
const MetaCUE = `
// Lifecycle customisations for a managed resource.
#Lifecycle: {
	create_before_destroy?: __bool
	prevent_destroy?:       __bool
	// Attribute names whose configuration changes are ignored, or ["*"].
	ignore_changes?: [...__string]
	// Refresh age: refresh the resource from the provider only when its
	// recorded state is older than this. "always" (the default), "never",
	// or a duration such as "30m", "6h" or "7d".
	refresh?: "always" | "never" | =~"^[0-9]+(ms|s|m|h|d)$"
}
`

// identityCUE is the marker every definition carries. pravo finds resources
// by these fields wherever they appear in a specification: $kind says what the
// struct is, $type which provider type, $source which provider.
func identityCUE(kind, typ, source string) string {
	return fmt.Sprintf("\t\t// Identity: pravo treats a struct that carries these as a %s.\n\t\t$kind:   %q\n\t\t$type:   %q\n\t\t$source: %q\n", kind, kind, typ, source)
}

// providerMeta is the identity and requirement fields of #Provider. $version,
// $path, $protocol and $address say which provider binary to run; the rest of
// the struct is the provider's own configuration.
func providerMeta(source string) string {
	return fmt.Sprintf(`	// Identity: pravo treats a struct that carries these as a provider.
	$kind:   "provider"
	$source: %q
	// Version constraint such as "~> 5.0". Leave out to accept any version.
	$version?: __string
	// Development override: a provider binary or its directory.
	$path?: __string
	// "tfplugin" (the default) or "tfplugin+reattach" for a provider that is
	// already running.
	$protocol?: "tfplugin" | "tfplugin+reattach"
	// With tfplugin+reattach: unix:///path or tcp://127.0.0.1:port.
	$address?: __string
	// The address this provider had before, such as "registry.opentofu.org/hashicorp/aws"
	// after moving to a copy in a container registry. Records written under the
	// old address are relabelled at the next plan. Leave it in place afterwards.
	$from?: __string
`, source)
}

// fromMeta lets a resource or data source say where its record used to be.
const fromMeta = `		// The address the record had before this resource was written here. Moves
		// the record to this address at the next plan.
		$from?: __string
`

// importMeta lets a managed resource adopt an existing object.
const importMeta = `		// The id of an existing object to bring under management, as the provider
		// understands it. Read at the next plan; leave it in place afterwards.
		$import?: __string
`

// discoveryMeta is what a discovery sets besides the scope that the list
// resource's own schema gives it.
const discoveryMeta = `		// The most objects one run lists. Leave out for the provider's own bound.
		$limit?: int & >0
		// Objects that are known and meant to stay unmanaged. An entry covers the objects whose id
		// or whole identity matches one of ids, or whose name matches one of names: * stands for
		// any run of characters and ? for one. They are still listed, and stop asking to be adopted.
		$ack?: [...{
			ids?:    [...__string]
			names?:  [...__string]
			reason?: __string
		}]
`

const resourceMeta = `		// Additional dependencies, as references to other resources.
		$depends_on?: [..._]
		$lifecycle?: #Lifecycle
`

const dataMeta = `		// Additional dependencies, as references to other resources.
		$depends_on?: [..._]
`

// GenerateCUE renders the provider schema as CUE source for package pkgName.
// The package exposes #Provider, #Resource.<type> and #Data.<type>.
func GenerateCUE(p *ProviderSchema, pkgName string, opts GenOptions) []byte {
	// Attribute names such as "number" or "string" would shadow CUE's
	// predeclared types inside the generated structs, so refer to the types
	// through their __-prefixed aliases when any label collides.
	builtinPrefix = ""
	if shadowsBuiltins(p) {
		builtinPrefix = "__"
	}
	var b bytes.Buffer
	if opts.Header != "" {
		fmt.Fprintf(&b, "// %s\n", opts.Header)
	}
	fmt.Fprintf(&b, "// Code generated by pravo. DO NOT EDIT.\n\npackage %s\n", pkgName)
	b.WriteString(MetaCUE)

	b.WriteString("\n// Provider configuration. A struct built from this is a provider. Build\n// resources through it: provider.#Resource.<type> & {...}.\n#Provider: {\n")
	b.WriteString(providerMeta(opts.Source))
	if p.Provider != nil && p.Provider.Block != nil {
		writeDoc(&b, p.Provider.Block.Description, "\t")
		writeBlockBody(&b, p.Provider.Block, "\t")
	}
	b.WriteString("}\n")

	res := opts.Resources
	if res == nil {
		res = p.SortedResourceNames()
	}
	b.WriteString("\n// Managed resource types.\n_#Resource: {\n")
	for _, name := range res {
		s := p.Resource(name)
		if s == nil {
			continue
		}
		writeDoc(&b, s.Block.Description, "\t")
		fmt.Fprintf(&b, "\t%s: {\n", fieldName(name))
		b.WriteString(identityCUE("resource", name, opts.Source))
		b.WriteString(fromMeta)
		b.WriteString(importMeta)
		b.WriteString(resourceMeta)
		writeBlockBody(&b, s.Block, "\t\t")
		b.WriteString("\t}\n")
	}
	b.WriteString("}\n")

	ds := opts.DataSources
	if ds == nil {
		ds = p.SortedDataSourceNames()
	}
	b.WriteString("\n// Data source types.\n_#Data: {\n")
	for _, name := range ds {
		s := p.DataSource(name)
		if s == nil {
			continue
		}
		writeDoc(&b, s.Block.Description, "\t")
		fmt.Fprintf(&b, "\t%s: {\n", fieldName(name))
		b.WriteString(identityCUE("data", name, opts.Source))
		b.WriteString(fromMeta)
		b.WriteString(dataMeta)
		writeBlockBody(&b, s.Block, "\t\t")
		b.WriteString("\t}\n")
	}
	b.WriteString("}\n")

	eph := opts.Ephemerals
	if eph == nil {
		eph = p.SortedEphemeralNames()
	}
	b.WriteString("\n// Ephemeral resource types: opened for the duration of a run, never recorded in state.\n_#Ephemeral: {\n")
	for _, name := range eph {
		s := p.Ephemeral(name)
		if s == nil {
			continue
		}
		writeDoc(&b, s.Block.Description, "\t")
		fmt.Fprintf(&b, "\t%s: {\n", fieldName(name))
		b.WriteString(identityCUE("ephemeral", name, opts.Source))
		b.WriteString(dataMeta)
		writeBlockBody(&b, s.Block, "\t\t")
		b.WriteString("\t}\n")
	}
	b.WriteString("}\n")

	lst := opts.Discoveries
	if lst == nil {
		lst = p.SortedListNames()
	}
	b.WriteString("\n// Discoveries: a list resource type with the scope to list it in. A discovery finds objects; it manages none.\n_#Discovery: {\n")
	for _, name := range lst {
		s := p.ListResource(name)
		if s == nil {
			continue
		}
		writeDoc(&b, s.Block.Description, "\t")
		fmt.Fprintf(&b, "\t%s: {\n", fieldName(name))
		b.WriteString(identityCUE("discovery", name, opts.Source))
		b.WriteString(discoveryMeta)
		writeBlockBody(&b, s.Block, "\t\t")
		b.WriteString("\t}\n")
	}
	b.WriteString("}\n")

	fns := opts.Functions
	if fns == nil {
		fns = p.SortedFunctionNames()
	}
	b.WriteString("\n// Provider-defined functions: a struct with args; the result is filled in at run time.\n_#Function: {\n")
	for _, name := range fns {
		f := p.Function(name)
		if f == nil {
			continue
		}
		doc := f.Description
		if doc == "" {
			doc = f.Summary
		}
		writeDoc(&b, doc, "\t")
		fmt.Fprintf(&b, "\t%s: {\n", fieldName(name))
		b.WriteString(identityCUE("call", name, opts.Source))
		var parts []string
		for _, prm := range f.Parameters {
			parts = append(parts, CUEType(prm.Type(), "\t\t\t"))
		}
		if f.Variadic != nil {
			parts = append(parts, "..."+CUEType(f.Variadic.Type(), "\t\t\t"))
		}
		var names []string
		for _, prm := range f.Parameters {
			names = append(names, prm.Name)
		}
		if f.Variadic != nil {
			names = append(names, f.Variadic.Name+"...")
		}
		fmt.Fprintf(&b, "\t\t// Positional arguments: %s\n", strings.Join(names, ", "))
		fmt.Fprintf(&b, "\t\targs: [%s]\n", strings.Join(parts, ", "))
		fmt.Fprintf(&b, "\t\t// Result, known after the call.\n\t\tresult: %s | null\n", CUEType(f.ReturnType(), "\t\t\t"))
		b.WriteString("\t}\n")
	}
	b.WriteString("}\n")
	// #Resource, #Data, #Ephemeral and #Function are members of #Provider, so a
	// resource is built through a provider instance: eu.#Resource.aws_s3_bucket
	// & {...}. That is how pravo knows which provider it uses. The definitions
	// themselves are written once, at package level, and each member is a
	// reference to them: CUE copies what a struct holds every time the struct is
	// unified, and a provider holds thousands of definitions.
	return referenceCatalogues(b.Bytes())
}

// referenceCatalogues adds the members #Resource, #Data, #Ephemeral and
// #Function to #Provider, each a reference to the definitions that follow the
// block at package level.
func referenceCatalogues(src []byte) []byte {
	lines := strings.Split(string(src), "\n")
	start, end := -1, -1
	for i, l := range lines {
		if start < 0 && strings.HasPrefix(l, "#Provider: {") {
			start = i
			continue
		}
		if start >= 0 && l == "}" {
			end = i
			break
		}
	}
	if start < 0 || end < 0 {
		return src
	}
	var out []string
	out = append(out, lines[:end]...)
	out = append(out,
		"",
		"\t// Definitions reached through a provider: a resource built through one uses it.",
		"\t// Managed resource types.",
		"\t#Resource: _#Resource",
		"\t// Data source types.",
		"\t#Data: _#Data",
		"\t// Ephemeral resource types: opened for the duration of a run, never recorded in state.",
		"\t#Ephemeral: _#Ephemeral",
		"\t// Discoveries: list resource types, each with the scope to list them in.",
		"\t#Discovery: _#Discovery",
		"\t// Provider-defined functions: a struct with args; the result is filled in at run time.",
		"\t#Function: _#Function",
	)
	out = append(out, lines[end:]...)
	return []byte(strings.Join(out, "\n"))
}

func writeDoc(b *bytes.Buffer, doc, indent string) {
	doc = strings.TrimSpace(doc)
	if doc == "" {
		return
	}
	for _, line := range strings.Split(doc, "\n") {
		line = strings.TrimRight(line, " \t")
		if line == "" {
			fmt.Fprintf(b, "%s//\n", indent)
		} else {
			fmt.Fprintf(b, "%s// %s\n", indent, line)
		}
	}
}

func writeBlockBody(b *bytes.Buffer, blk *Block, indent string) {
	for _, a := range blk.Attributes {
		writeAttribute(b, a, indent)
	}
	for _, nb := range blk.BlockTypes {
		writeDoc(b, nb.Block.Description, indent)
		inner := renderBlock(nb.Block, indent+"\t")
		var typ string
		switch nb.Nesting {
		case NestingList, NestingSet:
			typ = "[..." + inner + "]"
		case NestingMap:
			typ = "{[string]: " + inner + "}"
		default:
			typ = inner
		}
		fmt.Fprintf(b, "%s%s?: %s\n", indent, fieldName(nb.TypeName), typ)
	}
}

func renderBlock(blk *Block, indent string) string {
	var b bytes.Buffer
	b.WriteString("{\n")
	writeBlockBody(&b, blk, indent)
	b.WriteString(strings.TrimSuffix(indent, "\t") + "}")
	return b.String()
}

func writeAttribute(b *bytes.Buffer, a *Attribute, indent string) {
	writeDoc(b, a.Description, indent)
	var typ string
	if a.NestedType != nil {
		typ = renderNested(a.NestedType, indent+"\t")
	} else {
		typ = CUEType(a.Type(), indent+"\t")
	}
	var attrs []string
	if a.Sensitive {
		attrs = append(attrs, "sensitive")
	}
	if a.Deprecated {
		attrs = append(attrs, "deprecated")
	}
	if a.WriteOnly {
		attrs = append(attrs, "write_only")
	}
	suffix := ""
	if len(attrs) > 0 {
		suffix = " @pravo(" + strings.Join(attrs, ",") + ")"
	}
	name := fieldName(a.Name)
	switch {
	case a.Computed:
		fmt.Fprintf(b, "%s%s: %s | null%s\n", indent, name, typ, suffix)
	case a.Required:
		fmt.Fprintf(b, "%s%s: %s%s\n", indent, name, typ, suffix)
	default:
		fmt.Fprintf(b, "%s%s?: %s%s\n", indent, name, typ, suffix)
	}
}

func renderNested(o *Object, indent string) string {
	var b bytes.Buffer
	b.WriteString("{\n")
	for _, a := range o.Attributes {
		writeAttribute(&b, a, indent)
	}
	b.WriteString(strings.TrimSuffix(indent, "\t") + "}")
	inner := b.String()
	switch o.Nesting {
	case NestingList, NestingSet:
		return "[..." + inner + "]"
	case NestingMap:
		return "{[string]: " + inner + "}"
	default:
		return inner
	}
}

// CUEType renders a tftypes type as CUE source. indent is used for the inner
// lines of multi-line object types.
func CUEType(t tftypes.Type, indent string) string {
	switch {
	case t == nil:
		return "_"
	case t.Is(tftypes.String):
		return builtinPrefix + "string"
	case t.Is(tftypes.Number):
		return builtinPrefix + "number"
	case t.Is(tftypes.Bool):
		return builtinPrefix + "bool"
	case t.Is(tftypes.DynamicPseudoType):
		return "_"
	case t.Is(tftypes.List{}):
		return "[..." + CUEType(t.(tftypes.List).ElementType, indent) + "]"
	case t.Is(tftypes.Set{}):
		return "[..." + CUEType(t.(tftypes.Set).ElementType, indent) + "]"
	case t.Is(tftypes.Map{}):
		return "{[string]: " + CUEType(t.(tftypes.Map).ElementType, indent) + "}"
	case t.Is(tftypes.Tuple{}):
		parts := []string{}
		for _, et := range t.(tftypes.Tuple).ElementTypes {
			parts = append(parts, CUEType(et, indent))
		}
		return "[" + strings.Join(parts, ", ") + "]"
	case t.Is(tftypes.Object{}):
		obj := t.(tftypes.Object)
		if len(obj.AttributeTypes) == 0 {
			return "{}"
		}
		names := make([]string, 0, len(obj.AttributeTypes))
		for n := range obj.AttributeTypes {
			names = append(names, n)
		}
		sort.Strings(names)
		var b strings.Builder
		b.WriteString("{\n")
		for _, n := range names {
			fmt.Fprintf(&b, "%s%s?: %s\n", indent, fieldName(n), CUEType(obj.AttributeTypes[n], indent+"\t"))
		}
		b.WriteString(strings.TrimSuffix(indent, "\t") + "}")
		return b.String()
	}
	return "_"
}

// builtinPrefix is "" or "__"; set per GenerateCUE call.
var builtinPrefix string

var builtinTypeNames = map[string]bool{"string": true, "number": true, "bool": true, "int": true, "float": true, "bytes": true, "len": true}

func shadowsBuiltins(p *ProviderSchema) bool {
	if p.lazy != nil {
		return p.lazy.index.ShadowsBuiltins
	}
	found := false
	var visitBlock func(b *Block)
	var visitAttrs func(attrs []*Attribute)
	var visitType func(t tftypes.Type)
	visitType = func(t tftypes.Type) {
		switch tt := t.(type) {
		case tftypes.Object:
			for n, at := range tt.AttributeTypes {
				if builtinTypeNames[n] {
					found = true
				}
				visitType(at)
			}
		case tftypes.List:
			visitType(tt.ElementType)
		case tftypes.Set:
			visitType(tt.ElementType)
		case tftypes.Map:
			visitType(tt.ElementType)
		case tftypes.Tuple:
			for _, et := range tt.ElementTypes {
				visitType(et)
			}
		}
	}
	visitAttrs = func(attrs []*Attribute) {
		for _, a := range attrs {
			if builtinTypeNames[a.Name] {
				found = true
			}
			if a.NestedType != nil {
				visitAttrs(a.NestedType.Attributes)
			} else {
				visitType(a.Type())
			}
		}
	}
	visitBlock = func(b *Block) {
		if b == nil {
			return
		}
		visitAttrs(b.Attributes)
		for _, nb := range b.BlockTypes {
			if builtinTypeNames[nb.TypeName] {
				found = true
			}
			visitBlock(nb.Block)
		}
	}
	if p.Provider != nil {
		visitBlock(p.Provider.Block)
	}
	for _, s := range p.Resources {
		visitBlock(s.Block)
	}
	for _, s := range p.DataSources {
		visitBlock(s.Block)
	}
	for _, s := range p.Ephemerals {
		visitBlock(s.Block)
	}
	for _, s := range p.ListResources {
		visitBlock(s.Block)
	}
	return found
}

var cueKeywords = map[string]bool{
	"package": true, "import": true, "for": true, "in": true, "if": true, "let": true,
	"true": true, "false": true, "null": true,
}

// fieldName quotes a label when it is not a plain CUE identifier.
func fieldName(name string) string {
	if cueKeywords[name] || name == "" || name[0] == '_' || name[0] == '#' || name[0] == '$' {
		return strconv.Quote(name)
	}
	for i, r := range name {
		if r == '_' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (i > 0 && r >= '0' && r <= '9') {
			continue
		}
		return strconv.Quote(name)
	}
	return name
}
