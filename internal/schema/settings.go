package schema

import "strings"

// SettingsPackage is the package "pravo.dev/pravo", written by pravo init. It
// holds #Settings, the shape of the root's pravo block, so that a root can
// write $settings: pravo.#Settings & {...} and have editors complete it and a
// misspelt field rejected. It must stay in step with what
// config.extractSettings reads.
const SettingsPackage = `// Code generated by pravo init. DO NOT EDIT.

package pravo

// Embed #Movable in a definition so that its instances accept $from, which
// says where the resources inside used to be:
//
//	#Service: {pravo.#Movable, ...}
//	api: #Service & {$from: "web"}
#Movable: {
	// The path the resources of this struct had before. Every record below it
	// moves to the same place below this struct at the next plan.
	$from?: string
}

// A value the root publishes. It is recorded in state when the plan is
// applied and printed by "pravo output"; its name is the path it sits at.
//
//	url: pravo.#Output & {value: "https://\(host)"}
#Output: {
	$kind: "output"
	// What to publish. It must be concrete once the plan is applied, and it
	// must not use an ephemeral value, because it is recorded in state.
	value: _
	// What the value is for.
	description?: string
	// Hide the value where outputs are listed: in plans, in the apply summary
	// and in "pravo output" without a name. It is still recorded in state as it
	// is, and "pravo output <name>" and --json print it.
	sensitive?: bool
}

// A rule that every plan is judged by at apply. The apply refuses a plan with
// resource changes unless the rule holds for it; a rule is kept in the state as
// a signed version, and the signed start of each apply lists the versions that
// judged it. The name is the path the policy sits at. The rule is a CUE struct
// written here, in the specification, and is checked against #Plan, the
// document it is judged against, so that a misspelt field fails at once.
//
//	no_destroy: pravo.#Policy & {rule: summary: destroy: 0}
#Policy: {
	$kind: "policy"
	// Standalone CUE, using the standard library only, unified with the plan
	// document, which it must make concrete.
	rule: #Plan
	// What the policy is for.
	description?: string
}

// The document that a policy rule is judged against: the JSON of "pravo plan
// --json" without what only the state, the clock or the invocation can give
// (the blast radius, dependents, hints and the trace). A field that is not here
// cannot be read by a rule. Inside a list template, redeclare the fields the
// rule reads, with their schema:
//
//	changes: [...pravo.#Change & {addr: string, action: string, if action == "delete" {error(addr)}}]
#Plan: {
	// The layout version of the document.
	format: int
	// When the plan was made, RFC 3339.
	created: string
	// The labels of --actor and --reason, and the revision of the repository.
	actor?:        string
	reason?:       string
	git_revision?: string
	// True for "plan --destroy" and "destroy".
	destroy?: bool
	// Counts of actions. A replacement counts as an addition and a destruction.
	summary: {
		add:     int
		change:  int
		destroy: int
		read:    int
	}
	// How much of the graph the plan walked.
	stats: {
		total:     int
		reached:   int
		skipped:   int
		removed?:  int
		refreshed: int
		fresh:     int
		not_read:  int
		drifted:   int
		opened:    int
		called:    int
		imported:  int
		moved:     int
	}
	// One entry for each node the plan ran. A list with no entry is empty,
	// never null.
	changes: [...#Change]
	// The outputs by name; a value unknown until apply is {"$unknown": true}.
	outputs: [string]: _
	// The nodes and the end of a reservation made with --reserve.
	reservation?: {
		until: string
		addrs: [...string]
	}
	// The resolved version of each provider, by local name.
	providers: [string]: string
	// Set by a rule, not by the plan: the plan is applied only when the keys named here
	// have approved it ("pravo plan approve"), whatever else the policies in force say.
	// A rule sets it for the plans it picks out, with a disjunction (a rule cannot
	// test the plan with "if" outside a list template):
	//
	//	{summary: destroy: 0} | {summary: destroy: >0, approvals: min: 2}
	approvals?: {
		// How many distinct keys must have approved.
		min: int & >=1
		// The weakest role that counts as an approver.
		role: *"writer" | "admin"
		// Whether the key that stored the plan may approve it.
		self: *false | bool
	}
}

// What a plan does to a node. A replacement is an action
// of its own: it is not a delete followed by a create.
#Action: "create" | "update" | "replace" | "delete" | "read" | "open" | "call" | "move" | "no-op"

// One entry of changes in #Plan.
#Change: {
	// The CUE path of the declaration, such as pet or servers[0].
	addr: string
	mode: "managed" | "data" | "ephemeral" | "call"
	// The provider's type of the resource, or the name of the function.
	type: string
	// The last element of the path.
	name:   string
	action: #Action
	// The provider instance key, such as random or local.$primary.
	provider?: string
	reasons?: [...string]
	// The attributes that force a replacement.
	requires_replace?: [...string]
	// The recorded state of the object. Absent for a create.
	before?: {...}
	// The planned state of the object. Absent for a delete. A value the provider
	// computes at apply is {"$unknown": true}; an attribute that is not set is null.
	after?:      {...}
	deferred?:   bool
	skipped?:    bool
	refreshed?:  bool
	drifted?:    bool
	dependencies?: [...string]
	warnings?: [...string]
}

// The value of an environment variable, read when the run starts. It is an
// ordinary value, recorded wherever it is used. Use #SecretEnv for a secret.
//
//	region: pravo.#Env & {name: "AWS_REGION", default: "eu-west-1"}
#Env: {
	$kind: "env"
	// The name of the environment variable.
	name: string
	// Used when the variable is not set. Without it, an unset variable is an error.
	default?: string
	// What the variable holds.
	value: string
}

// The value of an environment variable that is a secret, read when the run
// starts. It is ephemeral: it is never written to state or to a saved plan, so
// it can be used in provider configuration, in write-only attributes and in
// other ephemeral resources, and nowhere that is recorded. An unset variable
// is an error.
//
//	db: pravo.#SecretEnv & {name: "DB_PASSWORD"}
#SecretEnv: {
	$kind: "secret_env"
	// The name of the environment variable.
	name: string
	// What the variable holds.
	value: string
}

// The outputs another root has recorded. Only its outputs.json is read, never
// its resources, so a reader needs access to that one object. It is read on
// every plan and apply, and its values are ordinary ones. An output that the
// other root marked sensitive is not included.
//
//	net: pravo.#RemoteOutputs & {state: {path: "../network/pravo.state"}}
//	... subnet: net.outputs.subnet_id
#RemoteOutputs: {
	$kind: "remote_outputs"
	// Where the other root keeps its state: a local directory (relative to
	// this root) or an S3-compatible bucket.
	state: #StateSettings
	// The outputs, by name. A name with dots, such as api.url, is a quoted
	// label: net.outputs["api.url"].
	outputs: {...}
}

// The shape of the $settings block.
#Settings: {
	// Where the state is kept: a local directory (the default), an
	// S3-compatible bucket or a server that speaks the http protocol.
	state?: #StateSettings

	// The default refresh age: "always", "never" or a duration such as
	// "30m", "6h" or "7d". A resource overrides it with $lifecycle.refresh.
	refresh?: "always" | "never" | =~"^[0-9]+(ms|s|m|h|d)$"

}

// The state backend is a choice with its own fields: S3 fields are an error
// with the local backend and a bucket is required for S3.
//
// #StateFields lists every field once so that editors, which do not complete
// through a disjunction, still offer them; the choice below decides which
// are valid together.
#StateSettings: #StateFields & (#LocalState | #S3State | #HTTPState)

#StateFields: {
	backend?:    "local" | "s3" | "http"
	path?:       string
	bucket?:     string
	prefix?:     string
	region?:     string
	endpoint?:   string
	path_style?: bool
	profile?:    string
	access_key?: string
	secret_key?: string
	url?:        string
	token?:      string
	username?:   string
	password?:   string
}

#LocalState: {
	// "local" is the default and may be left out.
	backend?: "local"
	// The directory of the state, relative to the root. Default pravo.state.
	path?: string
}

#S3State: {
	backend: "s3"
	// The bucket must exist; pravo does not create it.
	bucket: string
	// Key prefix, so several roots can share a bucket.
	prefix?: string
	// The region the bucket is in. Defaults to the AWS configuration, then
	// us-east-1.
	region?: string
	// The endpoint of an S3-compatible store; implies path-style addressing.
	endpoint?: string
	// Force path-style addressing.
	path_style?: bool
	// A shared-configuration profile.
	profile?: string
	// Static credentials. Prefer the environment or a profile: these end up
	// in the configuration.
	access_key?: string
	secret_key?: string
}

#HTTPState: {
	backend: "http"
	// The base URL of the state, such as https://state.example.com/team/app.
	// The server keeps one object for each key under it.
	url: string
	// A bearer token. Prefer PRAVO_STATE_TOKEN: a token here ends up in the
	// configuration.
	token?: string
	// Basic authentication, used when there is no token.
	username?: string
	password?: string
}
`

// PlanDocumentSource is the part of the pravo package that describes what a policy
// is and the document it is judged against: #Policy, #Plan, #Action and #Change, with
// their comments, as CUE.
func PlanDocumentSource() string {
	const from, to = "// A rule that every plan is judged by at apply.", "// The value of an environment variable, read when the run starts."
	i := strings.Index(SettingsPackage, from)
	j := strings.Index(SettingsPackage, to)
	if i < 0 || j < i {
		return ""
	}
	return strings.TrimSpace(SettingsPackage[i:j]) + "\n"
}
