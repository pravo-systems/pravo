// The judge (judge.go) holds a value against what it is, what it reads and what a provider made, and nothing else.
// These tests build small estates from the shapes that have gone wrong, and read every surface that sends a value.

const (
	typedRegion = "eu-north-1"              // typed into a sensitive attribute, and also an ordinary word everywhere
	typedPW     = "hunter22-typed-pw"       // typed into a sensitive attribute, and nowhere else by itself
	madePW      = "Zq8-made-by-provider-77" // generated by a provider: computed, sensitive, not optional
)

