func judgeSchemas() Schemas {
	fs := fakeSchemas().(ProviderSchemas)
	str := json.RawMessage(`"string"`)
	fs.PS.Resources["fake_pw"] = &schema.Schema{Version: 1, Block: &schema.Block{Attributes: []*schema.Attribute{
		{Name: "length", TypeJSON: json.RawMessage(`"number"`), Optional: true},
		{Name: "result", TypeJSON: str, Computed: true, Sensitive: true},
	}}}
	fs.PS.DataSources["fake_file_read"] = &schema.Schema{Version: 1, Block: &schema.Block{Attributes: []*schema.Attribute{
		{Name: "path", TypeJSON: str, Required: true},
		{Name: "content", TypeJSON: str, Computed: true},
	}}}
	return fs
}

func judgeLookup(src registry.Source, version string) (Schemas, bool) {
	if src.Type == "fake" && version == "1.0.0" {
		return judgeSchemas(), true
	}
	return nil, false
}

func judgeProject(t *testing.T) *project {
	t.Helper()
	dir := t.TempDir()
	writeSpec(t, dir, judgeSpecCUE)
	st, err := state.Open(filepath.Join(dir, "pravo.state"))
	if err != nil {
		t.Fatal(err)
	}
	txn := st.Begin("apply", "pravo apply")
	data := func(r *state.Resource) *state.Resource { r.Mode = "data"; return r }
	for _, r := range []*state.Resource{
		record("regionParam", "fake_db", `{"name":"param","blob":"`+typedRegion+`","zones":["arn:aws:ssm:`+typedRegion+`:123456789012:parameter/region"],"tags":{"Name":"`+typedRegion+`"}}`),
		data(record("zones", "fake_zones", `{"state":"available","names":["`+typedRegion+`a","`+typedRegion+`b"]}`)),
		record("reader", "fake_db", `{"name":"`+typedRegion+`a","zones":["`+typedRegion+`a","`+typedRegion+`b"],"settings":{"region":"`+typedRegion+`"}}`, "zones"),
		record("bucket", "fake_db", `{"name":"bucket","zones":["arn:aws:s3:::bucket-`+typedRegion+`"],"settings":{"region":"`+typedRegion+`"},"tags":{"region":"`+typedRegion+`"}}`),
		record("fromParam", "fake_db", `{"name":"from-param","tags":{"note":"`+typedRegion+`"}}`, "regionParam"),
		record("db", "fake_db", `{"name":"db","blob":"`+typedPW+`"}`),
		record("file", "fake_file", `{"path":"/tmp/cfg","content":"pw=`+typedPW+`"}`, "db"),
		data(record("read", "fake_file_read", `{"path":"/tmp/cfg","content":"pw=`+typedPW+`"}`, "file")),
		record("user", "fake_db", `{"name":"user","zones":["pw=`+typedPW+`"]}`, "read"),
		record("pw", "fake_pw", `{"length":22,"result":"`+madePW+`"}`),
		record("echo", "fake_db", `{"name":"echo","zones":["note: `+madePW+`"]}`),
		data(record("loose", "fake_file_read", `{"path":"/tmp/other","content":"`+madePW+`"}`)),
		record("taken", "fake_db", `{"name":"taken","zones":["`+madePW+`"]}`, "loose"),
	} {
		if err := st.Set(r, txn.ID()); err != nil {
			t.Fatal(err)
		}
		txn.Record(r.Address(), "create", 0, r.Revision)
	}
	if err := txn.Finish("applied", "13 created", true); err != nil {
		t.Fatal(err)
	}
	if err := st.SetOutputs(map[string]json.RawMessage{
		"regionName":  json.RawMessage(`"` + typedRegion + `a"`),
		"regionArn":   json.RawMessage(`"bucket"`),
		"regionValue": json.RawMessage(`"` + typedRegion + `"`),
		"fileContent": json.RawMessage(`"pw=` + typedPW + `"`),
		"looseOut":    json.RawMessage(`"` + madePW + `"`),
	}); err != nil {
		t.Fatal(err)
	}
	return start(t, dir, st, Options{Schemas: judgeLookup})
}

// attrShown reports whether the attribute is sent with its value whole: nothing in it is withheld, and it is not null or
// unknown.
func attrShown(a Attr) bool {
	if a.Redacted != "" || a.Null || a.Unknown {
		return false
	}
	for _, c := range a.Children {
		if c.Redacted != "" || (len(c.Children) > 0 && !attrShown(c)) {
			return false
		}
	}
	return true
}

func judgeAttr(t *testing.T, d Detail, name string) Attr {
	t.Helper()
	for _, a := range d.Attrs {
		if a.Name == name {
			return a
		}
	}
	t.Fatalf("%s has no attribute %s", d.Node.Addr, name)
	return Attr{}
}

// every text of the attribute, children included
func attrText(a Attr) string {
	b, _ := json.Marshal(a)
	return string(b)
}

func TestJudgeCases(t *testing.T) {
	p := judgeProject(t)
	type want struct {
		addr, attr string
		shown      bool
	}
	for _, w := range []want{
		// A region that a person keeps in a sensitive attribute is withheld where it is, and where something reads it,
		// and it withholds no other node's text.
		{"regionParam", "blob", false},
		{"regionParam", "name", true},
		{"regionParam", "zones", true}, // the ARN of the parameter says the region, and is not the value
		{"regionParam", "tags", true},
		{"fromParam", "tags", false}, // reads regionParam.blob
		{"fromParam", "name", true},
		{"bucket", "zones", true},
		{"bucket", "settings", true},
		{"bucket", "tags", true},
		{"zones", "names", true},
		{"zones", "state", true},
		{"reader", "name", true},
		{"reader", "zones", true},
		{"reader", "settings", true},
		// A password a person typed travels along the references: the file that embeds it, and the data source that reads
		// the file back, and what reads that.
		{"db", "blob", false},
		{"file", "content", false},
		{"file", "path", true},
		{"read", "content", false},
		{"read", "path", true},
		{"user", "zones", false},
		{"user", "name", true},
		// A password a provider made is looked for in every value.
		{"pw", "result", false},
		{"echo", "zones", false},
		{"echo", "name", true},
		{"loose", "content", false},
		{"taken", "zones", false},
		{"taken", "name", true},
	} {
		a := judgeAttr(t, p.detail(w.addr), w.attr)
		if attrShown(a) != w.shown {
			t.Errorf("%s.%s: shown = %v, want %v: %s", w.addr, w.attr, attrShown(a), w.shown, attrText(a))
		}
	}
	// A shown value is shown whole: its children are not withheld one by one.
	for _, c := range [][2]string{{"zones", "names"}, {"reader", "zones"}, {"bucket", "settings"}, {"bucket", "tags"}, {"regionParam", "zones"}} {
		a := judgeAttr(t, p.detail(c[0]), c[1])
		for _, ch := range a.Children {
			if ch.Redacted != "" {
				t.Errorf("%s.%s child %s is withheld: %s", c[0], c[1], ch.Name, attrText(a))
			}
		}
	}
	outs := map[string]Output{}
	for _, o := range p.graph().Outputs {
		outs[o.Name] = o
	}
	for name, redacted := range map[string]bool{"regionName": false, "regionArn": false, "regionValue": true, "fileContent": true, "looseOut": true} {
		o, ok := outs[name]
		if !ok {
			t.Errorf("no output %s", name)
			continue
		}
		if (o.Redacted != "") != redacted {
			t.Errorf("output %s: redacted = %q, want withheld = %v", name, o.Redacted, redacted)
		}
		// The page of the output says what the graph says.
		d := p.detail(name)
		if got := judgeAttr(t, d, "value").Redacted != ""; got != redacted {
			t.Errorf("output %s: the detail withholds = %v, the graph says %v", name, got, redacted)
		}
	}
}

// A value that is withheld for what it reads, or for what its text holds, says which, so that nobody has to guess.
func TestJudgeSaysWhy(t *testing.T) {
	p := judgeProject(t)
	if a := judgeAttr(t, p.detail("fromParam"), "tags"); a.Redacted != "derived" || !strings.Contains(a.Why, "regionParam.blob") {
		t.Errorf("fromParam.tags reads regionParam.blob: %+v", a)
	}
	if a := judgeAttr(t, p.detail("user"), "zones"); a.Redacted != "derived" || !strings.Contains(a.Why, "read.content") {
		t.Errorf("user.zones reads read.content: %+v", a)
	}
	if a := judgeAttr(t, p.detail("echo"), "zones"); len(a.Children) != 1 || a.Children[0].Redacted != "derived" || !strings.Contains(a.Children[0].Why, "provider made") {
		t.Errorf("echo.zones holds the password a provider made: %+v", a)
	}
	if a := judgeAttr(t, p.detail("read"), "content"); a.Redacted != "derived" || !strings.Contains(a.Why, "depends on") {
		t.Errorf("read.content holds the password of a node the data source depends on: %+v", a)
	}
	if a := judgeAttr(t, p.detail("fileContent"), "value"); a.Redacted != "derived" || !strings.Contains(a.Why, "read.content") {
		t.Errorf("the output reads read.content: %+v", a)
	}
	if a := judgeAttr(t, p.detail("looseOut"), "value"); a.Redacted != "derived" || a.Why == "" {
		t.Errorf("the output holds a made password: %+v", a)
	}
	// What is withheld for what it is needs no sentence: the page says it.
	if a := judgeAttr(t, p.detail("db"), "blob"); a.Redacted != "sensitive" || a.Why != "" {
		t.Errorf("db.blob: %+v", a)
	}
}

// Nothing that a person typed or a provider made is in any response, whatever the route.
func TestJudgeSendsNoSecret(t *testing.T) {
	p := judgeProject(t)
	var bodies []string
	bodies = append(bodies, string(p.get("/api/graph")))
	for _, n := range p.graph().Nodes {
		bodies = append(bodies, string(p.get("/api/detail?addr="+queryEscape(n.Addr))), string(p.get("/api/source?addr="+queryEscape(n.Addr))))
	}
	for _, path := range []string{"/api/fields?spec=zones", "/api/fields?spec=name", "/api/fields?spec=content"} {
		bodies = append(bodies, string(p.get(path)))
	}
	all := strings.Join(bodies, "\n")
	for _, s := range []string{typedPW, madePW} {
		if strings.Contains(all, s) {
			t.Errorf("the responses carry %q", s)
		}
	}
	// And the region, which is withheld where it is the value, is not withheld where it is only text: it is sent.
	if !strings.Contains(all, "arn:aws:ssm:"+typedRegion) {
		t.Error("the ARN of the parameter is withheld for holding the region")
	}
}

